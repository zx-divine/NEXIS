"""Injected generated pixels, never screenshots of the owner's desktop."""

from PySide6.QtGui import QPixmap, QColor
from PySide6.QtWidgets import QMessageBox

from nexis.ui.main_window import MainWindow


def preview_window(qtbot, db, tmp_path, platform, monkeypatch):
    window = MainWindow(db, tmp_path, platform)
    qtbot.addWidget(window)
    window.navigate("Screen Awareness")
    window.show()
    page = window.screen_awareness
    calls = []

    def generated_pixels():
        calls.append(1)
        image = QPixmap(64, 32)
        image.fill(QColor("black"))
        return image

    monkeypatch.setattr(page, "grab", generated_pixels)
    return window, page, calls


def test_screen_is_off_without_explicit_capture_and_denial_discards_nothing_remotely(qtbot, db, tmp_path, platform, monkeypatch):
    window, page, calls = preview_window(qtbot, db, tmp_path, platform, monkeypatch)
    assert not calls and not page.image and not page.enabled.isChecked()
    page.capture()
    assert not calls and not page.image
    page.enabled.setChecked(True)
    page.capture()
    assert calls == [1] and page.image.startswith(b"\x89PNG")
    manager = window.providers.manager
    manager.select(manager.save({"provider": "OmniRoute", "endpoint": "http://127.0.0.1:20128/v1", "model": "fixture"}))
    monkeypatch.setattr(QMessageBox, "question", lambda *args: QMessageBox.No)
    page.send()
    assert not page.jobs
    page.discard()
    page.send()
    assert not page.image and not page.jobs
    window.close()


def test_approved_vision_stays_separate_from_chat_tools_and_history(qtbot, db, tmp_path, platform, monkeypatch):
    window, page, calls = preview_window(qtbot, db, tmp_path, platform, monkeypatch)
    page.enabled.setChecked(True)
    page.capture()
    manager = window.providers.manager
    manager.select(manager.save({"provider": "OmniRoute", "endpoint": "http://127.0.0.1:20128/v1", "model": "fixture"}))
    seen = []

    def analyze(profile, image, question, cancel, **kwargs):
        seen.append((profile["model"], kwargs["consent"]))
        return "Injected explanation; no action"

    monkeypatch.setattr("nexis.ui.screen_page.analyze_image", analyze)
    monkeypatch.setattr(QMessageBox, "question", lambda *args: QMessageBox.Yes)
    page.send()
    qtbot.waitUntil(lambda: "Injected explanation" in page.answer.toPlainText(), timeout=3000)
    assert seen == [("fixture", True)] and not platform.calls
    assert not window.ai_jobs and not window.conversation_history
    window.navigate("Dashboard")
    assert not page.image and not page.answer.toPlainText()
    window.close()


def test_revoked_capture_grant_blocks_pixels_and_hard_mute_discards_preview(qtbot, db, tmp_path, platform, monkeypatch):
    window, page, calls = preview_window(qtbot, db, tmp_path, platform, monkeypatch)
    page.enabled.setChecked(True)
    grants = db.setting("access_permissions")
    grants["screen_capture"] = False
    db.set_setting("access_permissions", grants)
    page.capture()
    assert not calls and "Permission denied" in page.status.text()
    grants["screen_capture"] = True
    db.set_setting("access_permissions", grants)
    page.capture()
    window.set_microphone_muted(True)
    assert not page.image and not page.jobs
    window.close()


def test_discard_during_consent_invalidates_identical_recapture(qtbot, db, tmp_path, platform, monkeypatch):
    window, page, calls = preview_window(qtbot, db, tmp_path, platform, monkeypatch)
    page.enabled.setChecked(True)
    page.capture()
    manager = window.providers.manager
    manager.select(manager.save({"provider": "OmniRoute", "endpoint": "http://127.0.0.1:20128/v1", "model": "fixture"}))

    def discard_and_recapture(*args):
        page.discard()
        page.capture()  # Same generated bytes; the consent generation is different.
        return QMessageBox.Yes

    monkeypatch.setattr(QMessageBox, "question", discard_and_recapture)
    page.send()
    assert len(calls) == 2 and not page.jobs
    window.close()


def test_natural_screen_request_opens_preview_page_without_capture_or_network(qtbot, db, tmp_path, platform, monkeypatch):
    window, page, calls = preview_window(qtbot, db, tmp_path, platform, monkeypatch)
    window.navigate("Chat")
    window.conversation_request("Explain this error on my screen", "chat")
    assert not calls and not page.image and not page.jobs and not window.ai_jobs
    assert not window.conversation_history
    assert "Nothing has been captured" in window.chat.messages.item(window.chat.messages.count() - 1).text()
    window.close()
